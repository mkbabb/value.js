// SERVED MODEL: claude-opus-5-5
// judge synthesis — BUILD step, then the two runtime arms:
//   1. bundle (value.js actions + route-ts-compiler's positional stylesheet actions) over load-gen.ts and
//      run value.js's own grammar()/attach code to get the action-attached declarations;
//   2. emit the BUILD-TIME module (route-ts-compiler emitter, judge copy) → $OUT/css-grammar.<v>.generated.js
//      with a sha256 header over grammar text + emitter source (the drift key), for
//        synth     — the route's sound routing (F-b-4 cured: a non-ASCII lead reaches the alternatives that can take it)
//        synth-sa  — stock-ASCII routing (bbnf-lang 0.1.4's non-ASCII dispatch reproduced: the 0-mismatch proof)
//   3. bundle the runtime arms jx-aot-pos / jx-aot-pos-sa over load-run.ts (no front end, no parse-that).
//   node judge/harness/synth/gen.mjs
import { build, transform } from "esbuild";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { gzipSync } from "node:zlib";
import { OUT, REPO } from "../common.mjs";
const J = import.meta.dirname;
const TSC = path.join(REPO, "docs/tranches/X/parse-that/evidence/W7-research/route-ts-compiler");
const BBNF = path.join(REPO, "src/css/bbnf");
const rawPlugin = { name: "raw", setup(b) {
    b.onResolve({ filter: /\?raw$/ }, (a) => ({ path: path.resolve(a.resolveDir, a.path.replace(/\?raw$/, "").replace(/^VALUEJS\//, REPO + "/")), namespace: "raw" }));
    b.onLoad({ filter: /.*/, namespace: "raw" }, (a) => ({ contents: readFileSync(a.path, "utf8"), loader: "text" }));
} };
const swap = (loadFile, generated) => ({ name: "synth-swap", setup(b) {
    b.onResolve({ filter: /^\.\/load$/ }, (a) => (a.resolveDir === BBNF || a.resolveDir === path.join(TSC, "shim") ? { path: loadFile } : undefined));
    b.onResolve({ filter: /^\.\/stylesheet$/ }, (a) => (a.resolveDir === BBNF ? { path: path.join(TSC, "shim/stylesheet-positional.ts") } : undefined));
    if (generated) b.onResolve({ filter: /^synth-generated$/ }, () => ({ path: generated }));
} });
const common = { bundle: true, platform: "node", format: "esm", target: "node22", minify: false, logLevel: "warning",
    absWorkingDir: REPO, nodePaths: [path.join(REPO, "node_modules")], alias: { "@mkbabb/parse-that": `${TSC}/vendor/parse-that-head/index.ts` } };

// 1. the generator bundle
const genEntry = path.join(OUT, "synth-gen-entry.ts");
writeFileSync(genEntry, `export * as bbnf from "${BBNF}/index.ts";\nexport { emitModule, GRAMMAR_MODULES, OPTS } from "${J}/load-gen.ts";\n`);
const genOut = path.join(OUT, "synth-gen.mjs");
await build({ ...common, entryPoints: [genEntry], outfile: genOut, plugins: [rawPlugin, swap(path.join(J, "load-gen.ts"))] });
const G = await import(genOut);
const table = G.bbnf.grammar();
const grammarText = Object.values(G.GRAMMAR_MODULES).join("\n");
const emitterSrc = readFileSync(path.join(J, "emit-aot.ts"), "utf8") + readFileSync(path.join(TSC, "src/analysis.ts"), "utf8") + readFileSync(path.join(TSC, "src/regex.ts"), "utf8");
const sha = (s) => createHash("sha256").update(s).digest("hex");
const report = { built: new Date().toISOString(), grammarSha256: sha(grammarText), emitterSha256: sha(emitterSrc), variants: {} };
for (const [v, stockAscii, fb3] of [["synth", false, false], ["synth-sa", true, false], ["synth-fb3", false, true]]) {
    // the F-b-3 proof compiles through its OWN bundle instance, stripped before value.js's grammar() first compiles
    const I = fb3 ? await import(`${pathToFileURL(genOut).href}?fb3`) : G;
    if (fb3) I.OPTS.stripFb3 = true;
    const tbl = fb3 ? I.bbnf.grammar() : table;
    const header = `// GENERATED by judge/harness/synth/gen.mjs (route-ts-compiler emitter, build-time mode) — DO NOT EDIT\n// grammar sha256 ${report.grammarSha256} · emitter sha256 ${report.emitterSha256} · routing ${stockAscii ? "stock-ascii" : "sound"}\n`;
    const src = I.emitModule(tbl, { positional: true, stockAscii, header });
    const file = path.join(OUT, `css-grammar.${v}.generated.js`);
    writeFileSync(file, src);
    const min = (await transform(src, { minify: true, format: "esm" })).code;
    // determinism: a second emission is byte-identical
    const again = I.emitModule(tbl, { positional: true, stockAscii, header });
    report.variants[v] = { file, bytes: src.length, minBytes: min.length, gzipMinBytes: gzipSync(min).length, deterministic: again === src, sha256: sha(src) };
    const arm = { synth: "jx-aot-pos", "synth-sa": "jx-aot-pos-sa", "synth-fb3": "jx-aot-fb3" }[v];
    if (fb3) report.variants[v].strippedCaseClasses = I.OPTS.stripped;
    await build({ ...common, entryPoints: [path.join(OUT, "entry.ts")], outfile: path.join(OUT, `${arm}.mjs`), sourcemap: "external",
        plugins: [rawPlugin, swap(path.join(J, "load-run.ts"), file)] });
    const bundle = readFileSync(path.join(OUT, `${arm}.mjs`), "utf8");
    report.variants[v].arm = arm;
    report.variants[v].runtimeBundleHasParseThat = /class ParserState\b|class Parser\b/.test(bundle);
    report.variants[v].runtimeBundleHasFrontEnd = /BBNFToAST/.test(bundle);
}
writeFileSync(path.join(J, "..", "..", "results", "synth-build.json"), JSON.stringify(report, null, 1));
console.log(JSON.stringify(report, null, 1));
