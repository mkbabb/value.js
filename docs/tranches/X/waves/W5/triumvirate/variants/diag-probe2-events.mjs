import { chromium } from "/Users/mkbabb/Programming/value.js/node_modules/playwright-core/index.mjs";
const BASE = process.env.PROBE_BASE;
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, colorScheme: "light", deviceScaleFactor: 2 });
const page = await ctx.newPage();
const logs = [];
page.on("console", (m) => { if (["warning","error"].includes(m.type())) logs.push([m.type(), m.text().slice(0, 240)]); });
page.on("pageerror", (e) => logs.push(["pageerror", String(e.message).slice(0, 240)]));
await page.goto(`${BASE}/#/`, { waitUntil: "load" });
await page.waitForTimeout(7000);
await page.evaluate(() => { window.__w5t = []; });
await page.evaluate(() => { location.hash = "#/gradient"; });
const snap = () => page.evaluate(() => { const st = document.querySelector(".pane-wrapper--stage"); return { t: Math.round(performance.now()), events: window.__w5t.map((e) => e[0] + ":" + e[1]), stageKids: st?.children.length, stageTail: [...(st?.childNodes ?? [])].slice(-4).map((n) => n.nodeType === 8 ? "<!--" + n.data.slice(0, 20) + "-->" : n.nodeName + (n.className ? "." + String(n.className).slice(0, 30) : "")), stageDesc: st?.querySelectorAll("*").length, gradientRes: performance.getEntriesByType("resource").filter((r) => /Gradient|gradient/i.test(r.name)).map((r) => r.name.split("/").slice(-2).join("/").slice(0, 50) + "@" + Math.round(r.responseEnd)), pickerInDoc: !!document.querySelector(".hero-blob-anchor"), h1: document.querySelector("main h1")?.textContent }; });
await page.waitForTimeout(6000);
console.log("T+6s", JSON.stringify(await snap()));
await page.waitForTimeout(14000);
console.log("T+20s", JSON.stringify(await snap()));
console.log("logs", JSON.stringify(logs.filter((l) => !/MISCONFIGURED|api\.color|WebGL|adapters/.test(l[1])).slice(0, 10)));
await browser.close();
