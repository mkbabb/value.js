import { chromium } from "/Users/mkbabb/Programming/value.js/node_modules/playwright/index.mjs";
const OUT = new URL(".", import.meta.url).pathname;
const b = await chromium.launch({ headless: false });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, colorScheme: "light" });
const page = await ctx.newPage();
await page.goto("http://localhost:5173/#/cube", { waitUntil: "networkidle" });
await page.waitForTimeout(3500);
const opts = async () => page.evaluate(() => [...document.querySelectorAll("[role=option],[role=menuitem],[role=menuitemcheckbox]")].map(e => e.textContent.trim().slice(0,30) + " sel=" + (e.getAttribute("aria-selected")||e.getAttribute("data-state"))));
await page.getByRole("combobox", { name: "Select animation" }).first().click(); await page.waitForTimeout(700);
console.log("ANIM", await opts()); await page.screenshot({ path: OUT + "probe-anim-open.png" });
await page.keyboard.press("Escape"); await page.waitForTimeout(400);
const b2 = await page.locator(".glass-dock").first().boundingBox(); await page.mouse.move(b2.x + b2.width/2, b2.y + b2.height/2); await page.waitForTimeout(1100);
await page.getByRole("combobox", { name: "Controls tab" }).first().click(); await page.waitForTimeout(700);
console.log("TABS", await opts()); await page.screenshot({ path: OUT + "probe-tabs-open.png" });
await page.keyboard.press("Escape"); await page.waitForTimeout(400);
await page.getByRole("button", { name: "@mbabb menu" }).first().click(); await page.waitForTimeout(700);
console.log("MENU", await opts());
await page.keyboard.press("Escape");
await b.close();
