#!/usr/bin/env node
/**
 * HARVEST — pull every completed agent result out of the workflow journals onto disk.
 *
 * Why this exists. Workflow results reach the root as task notifications that are TRUNCATED, and a
 * session limit can kill 90% of a fan-out after its seats have already been paid for. The surviving
 * record lives only in `<session>/subagents/workflows/<runId>/journal.jsonl`. If that is never
 * harvested, a compaction silently discards completed work and the next session re-runs it — which
 * is both waste and, worse, a source of drift between two runs of the "same" audit.
 *
 * Run this after EVERY workflow completion, before re-deploying anything:
 *
 *   node docs/tranches/V/megatranche/workflows/harvest-journals.mjs
 *
 * Idempotent: re-harvesting the same journal rewrites the same bytes. Safe to run repeatedly.
 * Emits: registry/harvest/<workflow>.json  (raw, complete)
 *        registry/DEFECT-LEDGER.md          (readable, severity-ordered)
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, statSync } from "node:fs";
import { join, basename } from "node:path";

const SESSION = process.env.CLAUDE_SESSION_DIR
    || "/Users/mkbabb/.claude/projects/-Users-mkbabb-Programming-value-js/6614e90c-8bd6-434f-b017-5ad4277c6e5e";
const WF = join(SESSION, "subagents/workflows");
const OUT = "docs/tranches/V/megatranche/registry/harvest";

// runId -> stable human name. Unknown runs fall back to the runId, so a new workflow still harvests.
const NAMES = {
    "wf_0ddb79d6-164": "v-pi-receiving-audit",
    "wf_76f092b7-f4b": "history-audit-22-tranches",
    "wf_c88c8125-52c": "parser-band",
    "wf_3c8798e8-23e": "area-picker",
    "wf_e28d617f-9eb": "area-shell",
    "wf_6edda4a1-192": "area-workbenches",
    "wf_66b1fcba-daa": "area-core",
    "wf_dee4c83a-ec2": "area-scenes",
    "wf_22b7a7b7-97b": "area-palettes",
};

mkdirSync(OUT, { recursive: true });
if (!existsSync(WF)) { console.error(`no workflow dir at ${WF}`); process.exit(1); }

let total = 0;
const defects = [];
for (const dir of readdirSync(WF).sort()) {
    const j = join(WF, dir, "journal.jsonl");
    if (!existsSync(j) || !statSync(j).isFile()) continue;
    const name = NAMES[dir] ?? dir;
    const results = [];
    for (const line of readFileSync(j, "utf8").split("\n")) {
        if (!line.trim()) continue;
        let rec; try { rec = JSON.parse(line); } catch { continue; }
        if (rec.type !== "result") continue;
        results.push({ agentId: rec.agentId, key: rec.key, result: rec.result });
    }
    if (!results.length) continue;
    writeFileSync(join(OUT, `${name}.json`),
        JSON.stringify({ runId: dir, workflow: name, resultCount: results.length, results }, null, 1));
    total += results.length;
    for (const r of results) {
        const res = r.result;
        if (!res || typeof res !== "object" || !Array.isArray(res.defects)) continue;
        const subject = res.component ?? res.slug ?? (res.axis ?? "").slice(0, 60);
        for (const d of res.defects) {
            if (!d || typeof d !== "object") continue;
            defects.push({ wf: name, subject, axis: String(res.axis ?? "").split("—")[0].trim(), ...d,
                severity: String(d.severity ?? "?").toUpperCase() });
        }
    }
}

const ORDER = { BLOCKER: 0, MAJOR: 1, MINOR: 2, INFO: 3 };
defects.sort((a, b) => (ORDER[a.severity] ?? 9) - (ORDER[b.severity] ?? 9)
    || a.wf.localeCompare(b.wf) || String(a.subject).localeCompare(String(b.subject)));

const counts = defects.reduce((m, d) => (m[d.severity] = (m[d.severity] ?? 0) + 1, m), {});
const out = [
    "# HARVESTED DEFECT LEDGER — every defect returned by a completed challenger seat",
    "",
    "Generated by `workflows/harvest-journals.mjs` from `registry/harvest/*.json`, which is harvested",
    "from the workflow journals. **This file exists so that a session limit, a compaction, or a",
    "truncated notification cannot lose work that was already paid for.** Never re-run a seat whose",
    "rows are already here.",
    "",
    `**${defects.length} defects** from completed challenger seats: `
        + Object.entries(counts).sort((a, b) => (ORDER[a[0]] ?? 9) - (ORDER[b[0]] ?? 9))
            .map(([k, v]) => `${k} ${v}`).join(" · "),
    "",
    "> Status: these are **challenger** outputs. A defect here has NOT been adjudicated by a jury —",
    "> the jury seats were the ones most often killed by the rate wall. Treat every row as an",
    "> accusation with evidence attached, not as a finding of the formation. The jury pass decides.",
    "", "---", "",
];
let cur = null;
for (const d of defects) {
    if (d.severity !== cur) { cur = d.severity; out.push(`## ${cur}`, ""); }
    out.push(`### \`${d.subject}\` · ${d.id ?? ""} · ${d.axis}`, "");
    out.push(`**Defect.** ${d.defect ?? ""}`, "");
    if (d.mechanism) out.push(`**Mechanism.** ${d.mechanism}`, "");
    if (d.evidence) out.push("**Evidence.**", "", "```", String(d.evidence).slice(0, 1800), "```", "");
    if (d.reproduction) out.push(`**Reproduction.** ${String(d.reproduction).slice(0, 900)}`, "");
    if (d.proposedCure) out.push(`**Proposed cure.** ${String(d.proposedCure).slice(0, 1200)}`, "");
    out.push("---", "");
}
writeFileSync("docs/tranches/V/megatranche/registry/DEFECT-LEDGER.md", out.join("\n"));
console.log(`harvested ${total} agent results · ${defects.length} defects · ${JSON.stringify(counts)}`);
