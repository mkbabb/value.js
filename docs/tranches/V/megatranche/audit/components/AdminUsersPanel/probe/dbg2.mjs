import { webkit, chromium } from "playwright";
const E = process.argv[2] ?? "webkit";
const CORS = { "access-control-allow-origin": "*", "access-control-allow-headers": "authorization,content-type", "access-control-allow-methods": "GET,POST,PUT,PATCH,DELETE,OPTIONS" };
const NOW="2026-07-05T00:00:00.000Z";
const USERS=[{slug:"azure-fox-01",createdAt:NOW,paletteCount:4},{slug:"crimson-owl-77",createdAt:NOW,paletteCount:1}];
const b = await (E==="webkit"?webkit:chromium).launch();
const ctx = await b.newContext({viewport:{width:1440,height:900}});
await ctx.addInitScript(()=>localStorage.setItem("palette-admin-token","tok"));
const page = await ctx.newPage();
page.on("console", m=>{ if(m.type()!=="log"&&m.type()!=="debug") console.log("["+m.type()+"]", m.text().slice(0,140)); });
await page.route("**/sessions", r=>r.fulfill({status:200,contentType:"application/json",headers:CORS,body:'{"token":"t","userSlug":"u"}'}));
await page.route("**/admin/**", route=>{
  const u=new URL(route.request().url()), m=route.request().method();
  if(!u.pathname.startsWith("/admin/")) return route.continue();
  console.log("  API", m, u.pathname);
  const json=(b,s=200)=>route.fulfill({status:s,contentType:"application/json",headers:CORS,body:b});
  if(m==="OPTIONS") return route.fulfill({status:204,headers:CORS,body:""});
  if(m==="DELETE") return json('{"deleted":true,"palettesDeleted":0}');
  if(u.pathname==="/admin/users") return json(JSON.stringify({data:USERS,total:2,limit:50,offset:0}));
  return json('{"data":[],"total":0,"limit":50,"offset":0}');
});
await page.goto("http://localhost:9124/#/admin/users",{waitUntil:"domcontentloaded"});
await page.waitForSelector("main"); await new Promise(r=>setTimeout(r,2500));
await page.locator('button[aria-label="Delete user crimson-owl-77"]').click({force:true});
await new Promise(r=>setTimeout(r,600));
const btns = await page.locator('[role="dialog"] button').allInnerTexts();
console.log("dialog buttons:", JSON.stringify(btns));
await page.locator('[role="dialog"] button').filter({hasText:/Delete user/}).first().click({force:true});
await new Promise(r=>setTimeout(r,1500));
console.log("rows:", await page.locator('[role="button"][aria-expanded]').count());
console.log("text:", (await page.locator("main").innerText()).replace(/\n+/g," | ").slice(0,200));
await b.close();
